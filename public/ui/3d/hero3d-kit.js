      "#if defined(GL_EXT_shader_texture_lod)||__VERSION__>=300",
      "return sRGBToLinear(texture2DLodEXT(uEnv,q,lod)).rgb;",
      "#else",
      "return sRGBToLinear(texture2D(uEnv,q,lod)).rgb;",
      "#endif",
      "}",
      /* three's ACES filmic fit (exposure 1.12), applied here so no program variant depends
         on the renderer's tone mapping */
      "vec3 aces(vec3 c){c*=1.12/.6;c=mat3(.59719,.07600,.02840,.35458,.90834,.13383,.04823,.01566,.83777)*c;",
