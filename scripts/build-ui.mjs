// Builds the CyberNet UI layer ("Signal") from ui-src/ into public/ui/.
//
//   node scripts/build-ui.mjs           build and write the bundles (minified)
//   node scripts/build-ui.mjs --check   build in memory only; exit 1 and name the stale files if
//                                        public/ui differs from ui-src (run it before a deploy)
//   node scripts/build-ui.mjs --dev     unminified output with a marker per source file (debugging)
//   --out=<dir> / --src=<dir>           write somewhere else than public/ui, read another ui-src (tests)
//   CN_BUILD_FALLBACK=1                 skip esbuild and use the fallback minifier (tests)
//
// Bundles (the file names are referenced by the HTML heads; never rename them):
//   cybernet-ui.css        every ui-src/css/*.css partial, in name order (the SPA, public/index.html)
//   cybernet-ui.js         every ui-src/js/*.js module, in name order; each module runs inside its own
//                          try/catch, so one failing module never stops the ones after it (the error
//                          is logged and sent to window.CN_reportError from /cybernet-errors.js)
//   cybernet-ui-legal.css  the standalone documents (privacy, terms, refunds, acceptable-use, 404):
//                          the LEGAL_PARTIALS below in full, plus every rule from the other partials
//                          whose selector targets the cookie bar (DOC_RULES), kept in source order.
//                          The cookie bar can therefore live in any partial and still reach the
//                          legal pages. Add a partial to LEGAL_PARTIALS when a standalone page needs it.
//
// Minification uses esbuild (shipped with netlify-cli in node_modules). It understands strings,
// url() and comments, so text inside quotes (CSS `content`, data URIs, GLSL source) is never
// rewritten. If esbuild is missing, a conservative string-aware fallback is used for CSS and the
// JS is shipped with comments (a warning says so).
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const argv = process.argv.slice(2);
const args = new Set(argv);
const outArg = argv.find(a => a.startsWith("--out="));
const srcArg = argv.find(a => a.startsWith("--src="));
const outDir = outArg ? path.resolve(outArg.slice(6)) : path.join(root, "public", "ui");
const srcRoot = srcArg ? path.resolve(srcArg.slice(6)) : path.join(root, "ui-src");
const CHECK = args.has("--check");
const DEV = args.has("--dev");

const LEGAL_PARTIALS = ["00-tokens.css", "01-base.css", "70-legal.css", "90-a11y.css"];
const DOC_RULES = /#cnConsentBar|\.cn-consent|\.cn-cookie/;
// DESIGN.md performance budget, as brotli transfer size (a warning only; the build never fails on it)
const BUDGET = { "cybernet-ui.css": 45 * 1024, "cybernet-ui-legal.css": 12 * 1024, "cybernet-ui.js": 20 * 1024 };

const BANNER = {
  css: "/* CyberNet AI visual layer. Generated by scripts/build-ui.mjs from ui-src/css - edit the sources, not this file. */",
  legal: "/* CyberNet AI visual layer for the standalone legal pages and 404. Generated by scripts/build-ui.mjs from ui-src/css - edit the sources, not this file. */",
  js: "/* CyberNet AI motion layer. Generated by scripts/build-ui.mjs from ui-src/js - edit the sources, not this file. */",
};

let esbuild = null;
if (process.env.CN_BUILD_FALLBACK !== "1") { try { esbuild = await import("esbuild"); } catch { /* fallback below */ } }
if (!esbuild && !DEV) console.warn("[build-ui] esbuild not found: using the fallback CSS minifier and unminified JS. Run `npm install` to get it.");

async function sources(dir, ext) {
  const full = path.join(srcRoot, dir);
  const names = (await readdir(full)).filter(f => f.endsWith(ext)).sort();
  const files = [];
  for (const name of names) files.push({ name, text: (await readFile(path.join(full, name), "utf8")).trim() + "\n" });
  return files;
}

/* ---------- CSS ---------- */

async function minifyCss(css, label) {
  if (esbuild) {
    const r = await esbuild.transform(css, { loader: "css", minify: true, logLevel: "silent" });
    for (const w of r.warnings) console.warn(`[build-ui] ${label}: ${w.text}${w.location ? ` (line ${w.location.line}: ${w.location.lineText.trim().slice(0, 90)})` : ""}`);
    return r.code.trim();
  }
  return fallbackMinifyCss(css);
}

// Conservative CSS minifier used only without esbuild. It copies strings and url(...) verbatim,
// drops comments, collapses whitespace runs to one space and trims the space around { } ; , and >
// outside strings. It never touches ':' (a descendant `a :hover` differs from `a:hover`).
function fallbackMinifyCss(css) {
  let out = "", i = 0;
  const n = css.length, isWs = ch => ch === " " || ch === "\n" || ch === "\r" || ch === "\t" || ch === "\f";
  const tight = "{};,>";
  while (i < n) {
    const c = css[i];
    if (c === "/" && css[i + 1] === "*") { const j = css.indexOf("*/", i + 2); i = j < 0 ? n : j + 2; continue; }
    if (c === '"' || c === "'") {
      let j = i + 1;
      while (j < n && css[j] !== c) { if (css[j] === "\\") j++; j++; }
      out += css.slice(i, j + 1); i = j + 1; continue;
    }
    if ((c === "u" || c === "U") && /^url\(/i.test(css.slice(i, i + 4))) {
      let j = i + 4, q = null;
      while (j < n) {
        const d = css[j];
        if (q) { if (d === "\\") j++; else if (d === q) q = null; }
        else if (d === '"' || d === "'") q = d;
        else if (d === ")") break;
        j++;
      }
      out += css.slice(i, j + 1); i = j + 1; continue;
    }
    if (isWs(c)) {
      let j = i; while (j < n && isWs(css[j])) j++;
      const prev = out[out.length - 1], next = css[j];
      if (prev !== undefined && next !== undefined && !tight.includes(prev) && !tight.includes(next) && !(next === "/" && css[j + 1] === "*")) out += " ";
      i = j; continue;
    }
    if (tight.includes(c) && out.endsWith(" ")) out = out.slice(0, -1);
    out += c; i++;
  }
  return out.replace(/;}/g, "}").trim();
}

// Splits minified CSS into its top-level blocks, string-aware: [{ prelude, body }] (body null for
// statements such as @import). Used only to pick the cookie-bar rules for the legal bundle.
function blocks(css) {
  const list = [];
  let i = 0;
  const n = css.length;
  while (i < n) {
    let j = i, q = null, paren = 0;
    while (j < n) {
      const d = css[j];
      if (q) { if (d === "\\") j++; else if (d === q) q = null; }
      else if (d === '"' || d === "'") q = d;
      else if (d === "(") paren++;
      else if (d === ")") paren--;
      else if (!paren && (d === "{" || d === ";" || d === "}")) break;
      j++;
    }
    const prelude = css.slice(i, j).trim();
    if (j >= n || css[j] === "}") { i = j + 1; continue; }
    if (css[j] === ";") { if (prelude) list.push({ prelude, body: null }); i = j + 1; continue; }
    let k = j + 1, depth = 1; q = null;
    while (k < n && depth) {
      const d = css[k];
      if (q) { if (d === "\\") k++; else if (d === q) q = null; }
      else if (d === '"' || d === "'") q = d;
      else if (d === "{") depth++;
      else if (d === "}") depth--;
      k++;
    }
    list.push({ prelude, body: css.slice(j + 1, k - 1) });
    i = k;
  }
  return list;
}

const GROUPING = /^@(media|supports|container|layer|scope|document|starting-style)\b/i;
function pickRules(css, test) {
  let out = "";
  for (const b of blocks(css)) {
    if (b.body === null) continue;
    if (GROUPING.test(b.prelude)) { const inner = pickRules(b.body, test); if (inner) out += `${b.prelude}{${inner}}`; }
    else if (b.prelude[0] !== "@" && test.test(b.prelude)) out += `${b.prelude}{${b.body}}`;
  }
  return out;
}
function keyframesFor(css, picked) {
  let out = "";
  for (const b of blocks(css)) {
    const m = b.body !== null && /^@(?:-webkit-)?keyframes\s+([\w-]+)/i.exec(b.prelude);
    if (m && new RegExp(`(^|[^\\w-])${m[1]}([^\\w-]|$)`).test(picked)) out += `${b.prelude}{${b.body}}`;
  }
  return out;
}

async function buildCss(files) {
  if (DEV) return files.map(f => `/* ---- ${f.name} ---- */\n${f.text}`).join("\n");
  return minifyCss(files.map(f => f.text).join("\n"), "cybernet-ui.css");
}

async function buildLegalCss(files) {
  const missing = LEGAL_PARTIALS.filter(n => !files.some(f => f.name === n));
  if (missing.length) console.warn(`[build-ui] cybernet-ui-legal.css: missing partial(s) ${missing.join(", ")}`);
  const parts = [];
  for (const f of files) {
    if (LEGAL_PARTIALS.includes(f.name)) { parts.push(DEV ? `/* ---- ${f.name} ---- */\n${f.text}` : f.text); continue; }
    if (!DOC_RULES.test(f.text)) continue;
    const min = await minifyCss(f.text, f.name);
    const picked = pickRules(min, DOC_RULES);
    if (picked) parts.push((DEV ? `/* ---- ${f.name} (cookie bar rules) ---- */\n` : "") + picked + keyframesFor(min, picked));
  }
  const css = parts.join("\n");
  return DEV ? css : minifyCss(css, "cybernet-ui-legal.css");
}

/* ---------- JS ---------- */

async function buildJs(files) {
  const wrapped = files.map(f =>
    `/* ---- ${f.name} ---- */\ntry {\n${f.text}} catch (err) { if (window.console) console.error("[cn] ${f.name}", err); if (window.CN_reportError) window.CN_reportError(err, "ui module ${f.name}"); }\n`
  ).join("\n");
  if (DEV || !esbuild) return wrapped;
  const r = await esbuild.transform(wrapped, { loader: "js", minify: true, target: "es2019", legalComments: "none", logLevel: "silent" });
  for (const w of r.warnings) console.warn(`[build-ui] cybernet-ui.js: ${w.text}`);
  return r.code.trim();
}

/* ---------- write / check ---------- */

const css = await sources("css", ".css");
const js = await sources("js", ".js");
const outputs = [
  { file: "cybernet-ui.css", text: `${BANNER.css}\n${await buildCss(css)}\n`, from: css.length },
  { file: "cybernet-ui-legal.css", text: `${BANNER.legal}\n${await buildLegalCss(css)}\n`, from: LEGAL_PARTIALS.length },
  { file: "cybernet-ui.js", text: `${BANNER.js}\n${await buildJs(js)}\n`, from: js.length },
];

const kb = b => (b / 1024).toFixed(1) + " KB";
const stale = [];
if (!CHECK) await mkdir(outDir, { recursive: true });
for (const o of outputs) {
  const target = path.join(outDir, o.file);
  const current = existsSync(target) ? await readFile(target, "utf8") : null;
  const raw = Buffer.byteLength(o.text);
  const gz = zlib.gzipSync(o.text, { level: 9 }).length;
  const br = zlib.brotliCompressSync(o.text, { params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 11 } }).length;
  const budget = BUDGET[o.file];
  const over = !DEV && budget && br > budget ? `  (over the ${kb(budget)} brotli budget)` : "";
  if (current !== o.text) stale.push(o.file);
  if (!CHECK && current !== o.text) await writeFile(target, o.text);
  console.log(`${o.file.padEnd(22)} ${String(o.from).padStart(2)} source(s)  ${kb(raw).padStart(9)}  gzip ${kb(gz).padStart(8)}  brotli ${kb(br).padStart(8)}${over}${CHECK ? (current === o.text ? "  up to date" : "  STALE") : current === o.text ? "  unchanged" : "  written"}`);
}
if (CHECK && stale.length) {
  console.error(`[build-ui] public/ui is stale (${stale.join(", ")}). Run: node scripts/build-ui.mjs`);
  process.exit(1);
}
