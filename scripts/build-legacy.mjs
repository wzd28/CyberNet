// Builds the copies of the site's scripts that the pages actually load, in public/legacy/.
//
//   node scripts/build-legacy.mjs           build and write public/legacy/*.js
//   node scripts/build-legacy.mjs --check   build in memory only; exit 1 and name the stale files if
//                                            public/legacy differs from the sources (run it before a deploy)
//
// Why: the sources use ES2020 syntax (?. and ??). Older Android WebViews, such as the in-app
// browsers of news apps where the TikTok/Pangle ads run (Chrome 69 on Android 9), cannot parse
// it, so every one of these scripts failed and the page was dead for those visitors (browser
// error alerts of 21 Oct 2026). esbuild rewrites that syntax to ES2018; nothing else changes.
//
// Edit the sources (public/<name>.js), never public/legacy. The server (analyze.mts) and the
// tests keep using the sources. Each output is checked with acorn at ES2018, so a newer feature
// that esbuild cannot lower fails the build instead of reaching a visitor.
//
// After a rebuild, bump the ?v= of the changed files in public/index.html (and privacy.html).
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const outDir = path.join(root, "public", "legacy");

// Every first-party script a page loads that needs more than ES2018. The pages point at
// /legacy/<name>; the ES2017 ones (cybernet-errors.js, config.js, cybernet-howto.js) load as they are.
export const SCRIPTS = [
  "cybernet-consent.js",
  "cybernet-engine.js",
  "script.js",
  "cybernet-account-api-upgrade.js",
  "cybernet-business-team.js",
  "cybernet-final-ui-fix.js",
  "cybernet-legal-upgrade.js",
  "cybernet-privacy-controls.js",
  "cybernet-onboarding.js",
  "cybernet-admin-feedback.js",
];
const TARGET = "es2018";

let esbuild, acorn;
try { esbuild = await import("esbuild"); acorn = await import("acorn"); }
catch { console.error("[build-legacy] esbuild and acorn come with netlify-cli: run `npm install` first."); process.exit(1); }

const stale = [];
for (const name of SCRIPTS) {
  const source = await readFile(path.join(root, "public", name), "utf8");
  const { code } = await esbuild.transform(source, { loader: "js", target: TARGET, charset: "utf8", legalComments: "none" });
  const text = `/* Generated by scripts/build-legacy.mjs from public/${name} for older browsers (ES2018). Edit the source, not this file. */\n${code}`;
  try { acorn.parse(text, { ecmaVersion: 2018, sourceType: "script" }); }
  catch (err) { console.error(`[build-legacy] ${name} still needs more than ES2018 after esbuild: ${err.message}`); process.exit(1); }
  const file = path.join(outDir, name);
  const current = existsSync(file) ? await readFile(file, "utf8") : null;
  if (current === text) continue;
  stale.push(name);
  if (!CHECK) { await mkdir(outDir, { recursive: true }); await writeFile(file, text); }
}

if (CHECK && stale.length) {
  console.error(`[build-legacy] public/legacy is out of date: ${stale.join(", ")}. Run \`npm run build:legacy\`.`);
  process.exit(1);
}
console.log(CHECK ? "[build-legacy] public/legacy is up to date." : `[build-legacy] ${stale.length ? `wrote ${stale.join(", ")}` : "nothing to change"}.`);
