// Bundles the v2 redesign layer: v2-src/css/*.css -> public/v2/cybernet-v2.css (minified)
// and v2-src/js/*.js -> public/v2/cybernet-v2.js (files joined in name order).
//   node scripts/build-v2.mjs
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "public", "v2");
await mkdir(out, { recursive: true });

// Safe CSS minify: drop comments, collapse whitespace, trim around { } ; , and >.
// Values are never rewritten. Spaces inside url(...) and strings stay because only
// runs of whitespace collapse to one space and quotes/parentheses are left alone.
function minifyCss(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*([{};,>])\s*/g, "$1")
    .replace(/;}/g, "}")
    .trim();
}

async function bundle(dir, ext, target, banner) {
  const src = path.join(root, "v2-src", dir);
  const files = (await readdir(src)).filter(f => f.endsWith(ext)).sort();
  const parts = [];
  for (const f of files) parts.push(`/* ---- ${f} ---- */\n` + (await readFile(path.join(src, f), "utf8")).trim() + "\n");
  const body = parts.join("\n");
  const text = ext === ".css" ? `${banner}\n${minifyCss(body)}\n` : `${banner}\n${body}`;
  await writeFile(path.join(out, target), text);
  console.log(`${target}: ${files.length} file(s), ${(Buffer.byteLength(text) / 1024).toFixed(1)} KB`);
}
await bundle("css", ".css", "cybernet-v2.css", "/* CyberNet AI v2 visual layer. Generated by scripts/build-v2.mjs from v2-src/css - edit the sources, not this file. */");
await bundle("js", ".js", "cybernet-v2.js", "/* CyberNet AI v2 motion layer. Generated by scripts/build-v2.mjs from v2-src/js - edit the sources, not this file. */");
