create or replace function public.consume_analysis(
  p_user_id uuid
)
returns table (
  allowed boolean,
  used integer,
  daily_limit integer,
  plan text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_plan text := 'free';
  v_status text := 'inactive';
  v_limit integer := 5;
  v_used integer := 0;
begin
  -- plan lookup (changed 30 Oct 2026): Apple Pro counts as Pro; see public.plan_of
  v_plan := public.plan_of(p_user_id);
  v_status := case when v_plan = 'free' then 'inactive' else 'active' end;

  if
    v_plan = 'business'
    and v_status in ('active', 'trialing')
  then
    v_limit := 50;
  elsif
    v_plan = 'pro'
    and v_status in ('active', 'trialing')
  then
    v_limit := 15;
  else
    v_plan := 'free';
    v_limit := 3;
  end if;

  insert into public.daily_usage (
    user_id,
    usage_date,
    analysis_count
  )
  values (
    p_user_id,
    (now() at time zone 'utc')::date,
    0
  )
  on conflict (user_id, usage_date)
  do nothing;

  update public.daily_usage
  set
    analysis_count = analysis_count + 1,
    updated_at = now()
  where
    user_id = p_user_id
    and usage_date = (now() at time zone 'utc')::date
    and analysis_count < v_limit
  returning analysis_count
  into v_used;

  if v_used is null then
    select analysis_count
    into v_used
    from public.daily_usage
    where
      user_id = p_user_id
      and usage_date = (now() at time zone 'utc')::date;

    return query
    select
      false,
      coalesce(v_used, 0),
      v_limit,
      v_plan;

    return;
  end if;

  return query
  select
    true,
    v_used,
    v_limit,
    v_plan;
end;
$$;

