    select 1
    from public.apple_subscriptions a
    where a.user_id = p_user_id
      and a.plan = 'pro'
      and a.revoked_at is null
      and (a.expires_at > now() or a.grace_expires_at > now())
  ) then
    return 'pro';
  end if;

  return 'free';
end;
$$;

