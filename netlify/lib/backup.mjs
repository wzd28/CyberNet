// Every table in the public schema on 18 Oct 2026, in restore order: each
// table comes after the tables it references. `key` is the primary key (used
// to page through the rows in a stable order, and by the restore script),
// `identity` names a column whose numbers come from a sequence.
//
// To update the list, run this read-only query in the Supabase SQL editor,
// add the new table with its key, and place it after every table it
// references (the fk_public column):
//
//   select c.relname as table_name,
//     (select string_agg(a.attname::text, ',' order by array_position(i.indkey::int2[], a.attnum))
//        from pg_index i join pg_attribute a on a.attrelid = i.indrelid and a.attnum = any(i.indkey)
//       where i.indrelid = c.oid and i.indisprimary) as primary_key,
//     (select string_agg(distinct ft.relname::text, ',')
//        from pg_constraint fk join pg_class ft on ft.oid = fk.confrelid
//       where fk.conrelid = c.oid and fk.contype = 'f'
//         and ft.relnamespace = 'public'::regnamespace) as fk_public,
//     (select string_agg(a.attname::text || ':' || a.attidentity::text, ',')
//        from pg_attribute a where a.attrelid = c.oid and a.attidentity::text <> '') as identity
//   from pg_class c
//   where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p')
//   order by 1;
//
// (identity 'a' = generated always, 'd' = generated by default.)
//
// A public table that is missing from this list is still backed up: the
// REST API's own table list is checked on every run, extra tables are saved
// at the end, and the weekly email names them so the list can catch up.
