export function backupRecipient() {
  const configured = env("BACKUP_EMAIL_TO");
  return /^[^\s@<>,;]+@[^\s@<>,;]+\.[^\s@<>,;]+$/.test(configured) ? configured : BACKUP_TO;
}

// Returns a summary with no row data:
//   { status: "skipped", reason }                    no passphrase, nothing done
//   { status: "sent", filename, bytes, ... }         backup emailed
//   { status: "failed", error, alertSent }           nothing sent except the alert
export async function runBackup({
  trigger = "schedule",
  budgetMs = BUDGET_MS[trigger] || BUDGET_MS.schedule,
  maxAttachmentBytes = MAX_ATTACHMENT_BYTES
} = {}) {
  const passphrase = normalizePassphrase(env("BACKUP_PASSPHRASE"));
  if (!passphrase) {
    console.warn("CyberNet backup skipped: BACKUP_PASSPHRASE is not set in the Netlify environment variables. Nothing was read or sent. See docs/BACKUPS.md.");
    return { status: "skipped", reason: "BACKUP_PASSPHRASE is not set." };
  }

  const startedAt = Date.now();
  const createdAt = new Date(startedAt).toISOString();
  const finalDeadline = startedAt + budgetMs;
  const exportDeadline = finalDeadline - SEND_RESERVE_MS;
  const apiKey = env("RESEND_API_KEY");
  const to = backupRecipient();

  // Key derivation runs on the thread pool while the tables are read.
  const keyPromise = prepareKey(passphrase);
  keyPromise.catch(() => {});

  try {
    if (!apiKey) {
      throw new BackupError("The email service key (RESEND_API_KEY) is missing, so the backup could not be sent.", {
        hint: "Set RESEND_API_KEY in the Netlify environment variables, then run the backup again."
      });
    }

    const doc = await buildBackupDocument({ trigger, startedAt, deadline: exportDeadline });
    if (passphrase.length < 16) {
      doc.manifest.notes.push("The backup passphrase is shorter than 16 characters. A longer one (for example five random words) makes the file much harder to break. If you change it, keep the old one too: older backups still need it.");
    }

    const plain = gzipSync(Buffer.from(JSON.stringify(doc), "utf8"), { level: 9 });
    const encrypted = encryptWithKey(plain, await keyPromise);

    if (encrypted.length > maxAttachmentBytes) {
      throw new BackupError(
        `The backup is ${formatBytes(encrypted.length)} after compression and encryption, more than the ${formatBytes(maxAttachmentBytes)} an email can safely carry.`,
        { hint: "See \"When the backup gets too big\" in docs/BACKUPS.md. The simplest fix is Supabase Pro (US$25 a month), which makes daily backups itself." }
      );
    }
    if (encrypted.length > maxAttachmentBytes / 2) {
      doc.manifest.notes.push(`This backup is ${formatBytes(encrypted.length)}, more than half of the ${formatBytes(maxAttachmentBytes)} an email can carry. Plan the next step now: see "When the backup gets too big" in docs/BACKUPS.md.`);
    }
    if (Date.now() - startedAt > budgetMs * 0.6) {
      doc.manifest.notes.push(`This backup took ${Math.round((Date.now() - startedAt) / 1000)} seconds, close to the time limit of the free weekly job. Plan the next step now: see "When the backup gets too big" in docs/BACKUPS.md.`);
    }

    const filename = backupFileName(createdAt);
    const email = buildBackupEmail(doc.manifest, { filename, bytes: encrypted.length });
    const sent = await sendEmail(
      {
        from: BACKUP_FROM,
        to: [to],
        subject: email.subject,
        html: email.html,
        text: email.text,
        attachments: [{ filename, content: encrypted.toString("base64"), content_type: "application/octet-stream" }]
      },
      { apiKey, idempotencyKey: `cybernet-backup/${randomUUID()}`, deadline: finalDeadline }
    );
    if (!sent.ok) {
      throw new BackupError("The backup was made but the email service did not accept it.", {
        hint: "Check the Resend dashboard (Emails, then Logs) and the RESEND_API_KEY in Netlify, then run the backup again.",
        detail: sent.error
      });
    }

    const tableRows = Object.fromEntries(doc.manifest.restoreOrder.map((name) => [name, doc.manifest.tables[name].rows]));
    const summary = {
      status: "sent",
      to,
      filename,
      bytes: encrypted.length,
      authUsers: doc.manifest.authUsers.rows,
      tables: tableRows,
      notes: doc.manifest.notes,
      emailId: sent.id,
      ms: Date.now() - startedAt
    };
    console.log("CyberNet backup sent", JSON.stringify({ ...summary, notes: summary.notes.length }));
    return summary;
  } catch (error) {
    console.error("CyberNet backup failed:", error?.message || error, error?.detail || "");
    // The backup's own alert says what to do next; reportError adds the run to
    // the site-wide error log. Both run at once to stay inside the time limit.
    // reportError reads the message and stack (scrubbed), never `detail`.
    const [alertSent] = await Promise.all([
      sendAlert(error, { createdAt, trigger, apiKey, to, deadline: finalDeadline }),
      reportError(error, {
        fn: trigger === "manual" ? "backup-now" : "backup-weekly",
        label: "Database backup failed"
      })
    ]);
    return {
      status: "failed",
      error: error instanceof BackupError ? error.message : "Unexpected error.",
      alertSent
    };
  }
}

// Constant-time comparison for the manual trigger token.
export function tokenMatches(given, expected) {
  const a = createHash("sha256").update(String(given ?? "")).digest();
  const b = createHash("sha256").update(String(expected ?? "")).digest();
  return Boolean(given) && Boolean(expected) && timingSafeEqual(a, b);
}

