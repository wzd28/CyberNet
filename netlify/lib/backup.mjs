export function buildBackupEmail(manifest, { filename, bytes }) {
  const subject = backupSubject(manifest.createdAt, manifest.trigger);
  const tableNames = manifest.restoreOrder;
  const totalRows = tableNames.reduce((sum, name) => sum + manifest.tables[name].rows, 0);
  const made = `${manifest.createdAt.replace("T", " ").slice(0, 16)} UTC, ${manifest.trigger === "manual" ? "manual run" : "weekly schedule"}`;

  const text = [
    `Your ${manifest.trigger === "manual" ? "" : "weekly "}CyberNet AI backup is attached: ${filename} (${formatBytes(bytes)}).`,
    "",
    "It is encrypted. Only the backup passphrase (BACKUP_PASSPHRASE, kept in your password manager) can open it.",
    "Keep this email for 8 weeks, then delete it. Our Privacy Policy says backups are deleted after 8 weeks (docs/BACKUPS.md, step 7, has a monthly Gmail search for old backups).",
    "",
    "WHAT IS INSIDE",
    `Sign-in accounts (no passwords): ${manifest.authUsers.rows}`,
    ...tableNames.map((name) => `${name}: ${manifest.tables[name].rows}`),
    `Total table rows: ${totalRows}`,
    ...(manifest.notes.length ? ["", "PLEASE NOTE", ...manifest.notes.map((note) => `- ${note}`)] : []),
    "",
    "HOW TO RESTORE",
    ...RESTORE_STEPS.map((step, i) => `${i + 1}. ${step.text}${step.code ? ` ${step.code}` : ""}`),
    "",
    `Made ${made}, from ${manifest.source || "Supabase"}. Backup format ${manifest.formatVersion}, schema ${manifest.schemaVersion}${manifest.schemaFingerprint ? ` (fingerprint ${manifest.schemaFingerprint})` : ""}.`
  ].join("\n");

  const row = (label, value, strong = false) =>
    `<tr><td style="padding:6px 10px;border-top:1px solid rgba(148,180,204,0.14);color:${strong ? "#eaf6ff" : "#a9bccc"};font-size:13px;${strong ? "font-weight:700;" : ""}overflow-wrap:anywhere;">${escapeHtml(label)}</td>` +
    `<td style="padding:6px 10px;border-top:1px solid rgba(148,180,204,0.14);color:#eaf6ff;font-size:13px;text-align:right;white-space:nowrap;${strong ? "font-weight:700;" : ""}">${escapeHtml(value)}</td></tr>`;

  const html =
    CARD_OPEN +
    `<h1 ${H1}>${manifest.trigger === "manual" ? "Your CyberNet AI backup" : "Your weekly CyberNet AI backup"}</h1>` +
    `<p ${P}>The backup is attached: <strong style="color:#eaf6ff;">${escapeHtml(filename)}</strong> (${escapeHtml(formatBytes(bytes))}).</p>` +
    `<p ${P}>It is encrypted. Only the backup passphrase (BACKUP_PASSPHRASE, kept in your password manager) can open it. Keep this email for 8 weeks, then delete it: our Privacy Policy says backups are deleted after 8 weeks. Step 7 of docs/BACKUPS.md has a monthly Gmail search that finds the old ones.</p>` +
    (manifest.notes.length
      ? `<div style="background:rgba(250,204,21,0.08);border:1px solid rgba(250,204,21,0.35);border-radius:12px;padding:12px 14px;margin:16px 0 4px 0;">` +
        `<p style="color:#fde68a;font-size:13px;font-weight:700;margin:0 0 6px 0;">Please note</p>` +
        manifest.notes.map((note) => `<p style="color:#f5e7b0;font-size:13px;line-height:1.5;margin:0 0 6px 0;">${escapeHtml(note)}</p>`).join("") +
        `</div>`
      : "") +
    `<h2 ${H2}>What is inside</h2>` +
    `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="border-collapse:collapse;">` +
    row("Sign-in accounts (no passwords)", String(manifest.authUsers.rows)) +
    tableNames.map((name) => row(name, String(manifest.tables[name].rows))).join("") +
    row("Total table rows", String(totalRows), true) +
    `</table>` +
    `<h2 ${H2}>How to restore</h2>` +
    `<ol style="color:#a9bccc;font-size:14px;line-height:1.6;margin:0;padding-left:20px;">` +
    RESTORE_STEPS.map((step) => `<li style="margin:0 0 8px 0;">${escapeHtml(step.text)}${step.code ? `<code ${CODE}>${escapeHtml(step.code)}</code>` : ""}</li>`).join("") +
    `</ol>` +
    `<p ${SMALL}>Made ${escapeHtml(made)}, from ${escapeHtml(manifest.source || "Supabase")}. Backup format ${escapeHtml(manifest.formatVersion)}, schema ${escapeHtml(manifest.schemaVersion)}${manifest.schemaFingerprint ? ` (fingerprint ${escapeHtml(manifest.schemaFingerprint)})` : ""}.</p>` +
    CARD_CLOSE;

  return { subject, text, html };
}

export function buildAlertEmail(error, { createdAt, trigger }) {
  const subject = `CyberNet AI weekly backup FAILED ${createdAt.slice(0, 10)}${trigger === "manual" ? " (manual run)" : ""}`;
  const message = error instanceof BackupError ? error.message : "The backup stopped because of an unexpected error.";
  const hint = (error instanceof BackupError && error.hint) ||
    "Open Netlify, then Logs, then Functions, then backup-weekly, to see what went wrong. Then run the backup again.";
  const lines = [
    "This week's CyberNet AI backup was not made. No data was sent.",
    "",
    `What happened: ${message}`,
    `What to do next: ${hint}`,
    "",
    "Your earlier backup emails are not affected. Keep them until a new backup arrives.",
    "",
    `Run started ${createdAt.replace("T", " ").slice(0, 16)} UTC (${trigger === "manual" ? "manual run" : "weekly schedule"}).`
  ];
  const html =
    CARD_OPEN +
    `<h1 ${H1}>This week's backup was not made</h1>` +
    `<p ${P}>No data was sent. Your earlier backup emails are not affected; keep them until a new backup arrives.</p>` +
    `<h2 ${H2}>What happened</h2><p ${P}>${escapeHtml(message)}</p>` +
    `<h2 ${H2}>What to do next</h2><p ${P}>${escapeHtml(hint)}</p>` +
    `<p ${SMALL}>Run started ${escapeHtml(createdAt.replace("T", " ").slice(0, 16))} UTC (${trigger === "manual" ? "manual run" : "weekly schedule"}).</p>` +
    CARD_CLOSE;
  return { subject, text: lines.join("\n"), html };
}

// One POST to Resend, with a single retry on a rate limit, a server error or
// a dropped connection. The idempotency key stops a retry from sending twice.
async function sendEmail(payload, { apiKey, idempotencyKey, deadline }) {
  let lastError = null;
  for (let attempt = 1; attempt <= 2; attempt += 1) {
    const timeLeft = remaining(deadline);
    if (timeLeft < 1500) break;
    try {
      const response = await fetch(RESEND_URL, {
        method: "POST",
        headers: {
          Authorization: `Bearer ${apiKey}`,
          "Content-Type": "application/json",
          "Idempotency-Key": idempotencyKey
        },
        body: JSON.stringify(payload),
        signal: AbortSignal.timeout(Math.min(15_000, timeLeft))
      });
      if (response.ok) {
        const data = await response.json().catch(() => ({}));
        return { ok: true, id: data?.id || null };
      }
      lastError = `HTTP ${response.status} ${await bodyText(response)}`;
      if (response.status !== 429 && response.status < 500) break;
    } catch (error) {
      lastError = isTimeout(error) ? "timed out" : String(error?.message || error);
    }
    if (attempt === 1) await new Promise((resolve) => setTimeout(resolve, 600));
  }
  return { ok: false, error: lastError || "no time left to send" };
}

async function sendAlert(error, { createdAt, trigger, apiKey, to, deadline }) {
  if (!apiKey) return false;
  const email = buildAlertEmail(error, { createdAt, trigger });
  const result = await sendEmail(
    { from: BACKUP_FROM, to: [to], subject: email.subject, html: email.html, text: email.text },
    { apiKey, idempotencyKey: `cybernet-backup-alert/${randomUUID()}`, deadline: Math.max(deadline, Date.now() + 4000) }
  );
  if (!result.ok) console.error("CyberNet backup: the failure alert email could not be sent", result.error);
  return result.ok;
}

