// `message` is written for the owner and goes into the alert email; it never
// contains row data. `detail` is for the function log only.
export class BackupError extends Error {
  constructor(message, { hint = "", detail = "" } = {}) {
    super(message);
    this.name = "BackupError";
    this.hint = hint;
    this.detail = detail;
  }
}

function isTimeout(error) {
  return error?.name === "TimeoutError" || error?.name === "AbortError";
}

function remaining(deadline) {
  return deadline - Date.now();
}

function requestTimeout(deadline) {
  return Math.max(1000, Math.min(REQUEST_TIMEOUT_MS, remaining(deadline)));
}

const TOO_SLOW_HINT =
  "The backup has grown past what the free weekly job can read in its time limit. " +
  "See \"When the backup gets too big\" in docs/BACKUPS.md.";

function checkDeadline(deadline, what) {
  if (remaining(deadline) <= 0) {
    throw new BackupError(`The backup ran out of time while ${what}.`, { hint: TOO_SLOW_HINT });
  }
}

async function bodyText(response) {
  return (await response.text().catch(() => "")).slice(0, 300);
}

