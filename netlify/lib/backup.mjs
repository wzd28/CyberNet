function supabaseConfig() {
  const url = env("SUPABASE_URL").replace(/\/+$/, "");
  const serviceKey = env("SUPABASE_SERVICE_ROLE_KEY") || env("SUPABASE_SECRET_KEY");
  if (!url || !serviceKey) {
    throw new BackupError("The Supabase server settings are missing, so the database could not be read.", {
      hint: "Check that SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY (or SUPABASE_SECRET_KEY) are set in the Netlify environment variables."
    });
  }
  return { url, serviceKey };
}

// Every /rest/v1 read retries Supabase's passing 401 PGRST303 "JWT issued at
// future" (netlify/lib/supabase-retry.mjs), inside the same per-request timeout.
const REST_RETRY = { ...RETRY_STANDARD, label: "backup" };

function serviceHeaders(cfg, extra = {}) {
  return { apikey: cfg.serviceKey, Authorization: `Bearer ${cfg.serviceKey}`, ...extra };
}

// "0-999/1234", "*/0" or "0-9/*" -> { start, end, total }
export function parseContentRange(value) {
  const match = /^\s*(?:(\d+)-(\d+)|\*)\/(\d+|\*)\s*$/.exec(String(value || ""));
  if (!match) return { start: null, end: null, total: null };
  return {
    start: match[1] === undefined ? null : Number(match[1]),
    end: match[2] === undefined ? null : Number(match[2]),
    total: match[3] === "*" ? null : Number(match[3])
  };
}

// The REST API's description of the public schema: which tables exist, their
// columns and primary keys. Used to find tables missing from TABLES and to
// fingerprint the schema. A failure here only adds a note to the email.
async function discoverSchema(cfg, deadline) {
  try {
    const response = await fetchWithJwtRetry(`${cfg.url}/rest/v1/`, {
      headers: serviceHeaders(cfg, { Accept: "application/openapi+json" }),
      signal: AbortSignal.timeout(requestTimeout(deadline))
    }, REST_RETRY);
    if (!response.ok) {
      return { ok: false, detail: `HTTP ${response.status} ${await bodyText(response)}` };
    }
    const spec = await response.json();
    const definitions = spec?.definitions;
    if (!definitions || typeof definitions !== "object") return { ok: false, detail: "no definitions in the API description" };

    const tables = {};
    for (const name of Object.keys(definitions).sort()) {
      const properties = definitions[name]?.properties || {};
      const columns = Object.keys(properties).sort();
      tables[name] = {
        columns: Object.fromEntries(columns.map((column) => [column, String(properties[column]?.format || properties[column]?.type || "")])),
        key: columns.filter((column) => String(properties[column]?.description || "").includes("<pk/>"))
      };
    }
    const fingerprint = createHash("sha256")
      .update(JSON.stringify(Object.fromEntries(Object.entries(tables).map(([name, t]) => [name, t.columns]))))
      .digest("hex")
      .slice(0, 16);
    return { ok: true, tables, fingerprint };
  } catch (error) {
    return { ok: false, detail: isTimeout(error) ? "timed out" : String(error?.message || error) };
  }
}

// Reads one table page by page with Range headers, in primary-key order so
// the pages do not overlap. The page size the server actually returns is
// taken from Content-Range, so a lower server limit still pages correctly.
export async function exportTable(cfg, table, deadline) {
  const order = table.key?.length
    ? `&order=${table.key.map((column) => `${encodeURIComponent(column)}.asc`).join(",")}`
    : "";
  const rows = [];
  let offset = 0;
  let counted = null;

  for (let page = 0; ; page += 1) {
    if (page >= MAX_PAGES) {
      throw new BackupError(`Reading the ${table.name} table did not finish after ${MAX_PAGES} pages.`, { hint: TOO_SLOW_HINT });
    }
    checkDeadline(deadline, `reading the ${table.name} table`);

    let response;
    try {
      response = await fetchWithJwtRetry(`${cfg.url}/rest/v1/${encodeURIComponent(table.name)}?select=*${order}`, {
        headers: serviceHeaders(cfg, {
          Accept: "application/json",
          "Range-Unit": "items",
          Range: `${offset}-${offset + PAGE_SIZE - 1}`,
          Prefer: "count=exact"
        }),
        signal: AbortSignal.timeout(requestTimeout(deadline))
      }, REST_RETRY);
    } catch (error) {
      if (isTimeout(error)) throw new BackupError(`Reading the ${table.name} table took too long.`, { hint: TOO_SLOW_HINT });
      throw new BackupError(`The database could not be reached while reading the ${table.name} table.`, {
        hint: "This is usually temporary. Run the backup again later (see docs/BACKUPS.md, \"Run a backup now\").",
        detail: String(error?.message || error)
      });
    }

    // Past the last row (the table shrank while it was being read).
    if (response.status === 416) break;

    if (response.status === 404 && page === 0) {
      return { rows: [], counted: 0, missing: true };
    }

    if (!response.ok) {
      throw new BackupError(`The database refused to read the ${table.name} table (HTTP ${response.status}).`, {
        hint: "Check the backup-weekly function log in Netlify for the details, then run the backup again.",
        detail: await bodyText(response)
      });
    }

    const batch = await response.json().catch(() => null);
    if (!Array.isArray(batch)) {
      throw new BackupError(`The database sent an unexpected answer for the ${table.name} table.`, {
        hint: "Run the backup again. If it keeps happening, check the backup-weekly function log in Netlify."
      });
    }

    const range = parseContentRange(response.headers.get("content-range"));
    if (range.total !== null) counted = range.total;

    for (const row of batch) rows.push(row);
    if (!batch.length) break;
    offset += batch.length;
    if (counted !== null && offset >= counted) break;
  }

  return { rows, counted: counted ?? rows.length, missing: false };
}

export function pickAuthUser(user) {
  const out = {};
  for (const field of AUTH_USER_FIELDS) {
    if (user?.[field] !== undefined) out[field] = user[field];
  }
  // Which sign-in methods the account had (for example email, google), so a
  // restore can tell people how to get back in. The identity details
  // themselves (names, photos, provider ids) are not kept.
  out.identity_providers = [...new Set((Array.isArray(user?.identities) ? user.identities : [])
    .map((identity) => identity?.provider)
    .filter((provider) => typeof provider === "string" && provider))].sort();
  return out;
}

// Reads every sign-in account through the Auth admin API, page by page.
export async function exportAuthUsers(cfg, deadline) {
  const users = [];
  const seen = new Set();
  let counted = null;

  for (let page = 1; ; page += 1) {
    if (page > MAX_PAGES) {
      throw new BackupError(`Reading the sign-in accounts did not finish after ${MAX_PAGES} pages.`, { hint: TOO_SLOW_HINT });
    }
    checkDeadline(deadline, "reading the sign-in accounts");

    let response;
    try {
      response = await fetch(`${cfg.url}/auth/v1/admin/users?page=${page}&per_page=${AUTH_PAGE_SIZE}`, {
        headers: serviceHeaders(cfg, { Accept: "application/json" }),
        signal: AbortSignal.timeout(requestTimeout(deadline))
      });
    } catch (error) {
      if (isTimeout(error)) throw new BackupError("Reading the sign-in accounts took too long.", { hint: TOO_SLOW_HINT });
      throw new BackupError("Supabase Auth could not be reached while reading the sign-in accounts.", {
        hint: "This is usually temporary. Run the backup again later (see docs/BACKUPS.md, \"Run a backup now\").",
        detail: String(error?.message || error)
      });
    }

    if (!response.ok) {
      throw new BackupError(`Supabase Auth refused to list the sign-in accounts (HTTP ${response.status}).`, {
        hint: "Check that the service role key in Netlify is current, then run the backup again.",
        detail: await bodyText(response)
      });
    }

    const body = await response.json().catch(() => null);
    const list = Array.isArray(body) ? body : Array.isArray(body?.users) ? body.users : null;
    if (!list) {
      throw new BackupError("Supabase Auth sent an unexpected answer for the sign-in accounts.", {
        hint: "Run the backup again. If it keeps happening, check the backup-weekly function log in Netlify."
      });
    }

    const total = response.headers.get("x-total-count");
    if (total !== null && total !== "" && Number.isFinite(Number(total))) counted = Number(total);

    let added = 0;
    for (const user of list) {
      const id = user?.id;
      if (!id || seen.has(id)) continue;
      seen.add(id);
      users.push(pickAuthUser(user));
      added += 1;
    }

    // An empty page, a page with nothing new (the server ignored `page`), or
    // the reported total reached: done.
    if (!list.length || !added) break;
    if (counted !== null && users.length >= counted) break;
  }

  return { users, counted: counted ?? users.length };
}

// Runs `worker` over `items`, at most `limit` at a time. After the first
// failure no new item is started, so a broken run stops reading quickly.
async function runPool(items, limit, worker) {
  const results = new Array(items.length);
  let next = 0;
  let failed = false;
  const lanes = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (!failed && next < items.length) {
      const index = next;
      next += 1;
      try {
        results[index] = await worker(items[index], index);
      } catch (error) {
        failed = true;
        throw error;
      }
    }
  });
  await Promise.all(lanes);
  return results;
}

// Reads everything and assembles the backup document (unencrypted, in memory).
export async function buildBackupDocument({ trigger = "schedule", startedAt = Date.now(), deadline } = {}) {
  const cfg = supabaseConfig();
  const exportDeadline = deadline ?? startedAt + BUDGET_MS.schedule - SEND_RESERVE_MS;
  const notes = [];

  const schema = await discoverSchema(cfg, exportDeadline);
  const known = new Set(TABLES.map((t) => t.name));
  const excluded = new Set(EXCLUDED_TABLES);

  const plan = TABLES.map((t) => ({ ...t, found: "list" }));
  let extras = [];
  if (schema.ok) {
    extras = Object.keys(schema.tables)
      .filter((name) => !known.has(name) && !excluded.has(name))
      .map((name) => ({ name, key: schema.tables[name].key, found: "auto" }));
    plan.push(...extras);
  } else {
    console.warn("CyberNet backup: could not read the REST API table list", schema.detail);
    notes.push("The list of tables could not be checked this week, so only the tables already in the backup list were saved.");
  }

  const [tableResults, auth] = await Promise.all([
    runPool(plan, TABLE_CONCURRENCY, (table) => exportTable(cfg, table, exportDeadline)),
    exportAuthUsers(cfg, exportDeadline)
  ]);

  const tables = {};
  const manifestTables = {};
  const restoreOrder = [];
  const missing = [];
  plan.forEach((table, index) => {
    const result = tableResults[index];
    if (result.missing) {
      missing.push(table.name);
      return;
    }
    tables[table.name] = result.rows;
    restoreOrder.push(table.name);
    manifestTables[table.name] = {
      rows: result.rows.length,
      counted: result.counted,
      key: table.key || [],
      ...(table.identity ? { identity: table.identity } : {}),
      ...(table.identityAlways ? { identityAlways: true } : {}),
      found: table.found
    };
    if (result.rows.length !== result.counted) {
      notes.push(`${table.name} changed while the backup was running (${result.rows.length} rows saved, ${result.counted} counted). The next backup will catch up.`);
    }
  });

  // A wrong project address or a broken API would make every table look
  // missing. That must never pass as an (empty) backup.
  if (TABLES.every((table) => missing.includes(table.name))) {
    throw new BackupError("None of the database tables could be found, so no backup was made.", {
      hint: "Check that SUPABASE_URL in the Netlify environment variables points to the CyberNet project, then run the backup again."
    });
  }

  if (extras.length) {
    notes.push(`New tables that are not in the backup list yet were saved anyway: ${extras.map((t) => t.name).join(", ")}. Add them to TABLES in netlify/lib/backup.mjs.`);
  }
  const missingListed = missing.filter((name) => known.has(name));
  if (missingListed.length) {
    notes.push(`Tables in the backup list that no longer exist were skipped: ${missingListed.join(", ")}. Remove them from TABLES in netlify/lib/backup.mjs.`);
  }
  if (auth.users.length !== auth.counted) {
    notes.push(`Sign-in accounts changed while the backup was running (${auth.users.length} saved, ${auth.counted} counted). The next backup will catch up.`);
  }

  let source = "";
  try { source = new URL(cfg.url).host; } catch { source = ""; }

  return {
    manifest: {
      format: "cybernet-ai-backup",
      formatVersion: FORMAT.version,
      schemaVersion: SCHEMA_VERSION,
      schemaFingerprint: schema.ok ? schema.fingerprint : null,
      createdAt: new Date(startedAt).toISOString(),
      trigger,
      source,
      restoreOrder,
      tables: manifestTables,
      authUsers: { rows: auth.users.length, counted: auth.counted },
      skippedTables: missing,
      notes
    },
    tables,
    authUsers: auth.users
  };
}

