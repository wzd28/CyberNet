function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
}

export function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} bytes`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

function utcStamp(iso) {
  // 2026-10-18T00:00:12.345Z -> { date: "2026-10-18", time: "0000" }
  return { date: iso.slice(0, 10), time: iso.slice(11, 13) + iso.slice(14, 16) };
}

export function backupFileName(createdAt) {
  const { date, time } = utcStamp(createdAt);
  return `cybernet-backup-${date}-${time}utc.cnbk`;
}

export function backupSubject(createdAt, trigger) {
  return `CyberNet AI weekly backup ${createdAt.slice(0, 10)}${trigger === "manual" ? " (manual run)" : ""}`;
}

