// Weekly encrypted database backup (launch checklist item 9).
//
// The Supabase free plan has no automatic backups, so this exports the data
// itself through the same service-role REST API the other functions use:
// every table in the public schema, plus the sign-in accounts (account
// details only, never password hashes or tokens). The export is one JSON
// document. It is gzipped, encrypted with AES-256-GCM under a key derived from
// the BACKUP_PASSPHRASE environment variable, and emailed as an attachment
// through Resend. Without the passphrase nothing is read and nothing is sent,
// and nothing unencrypted ever leaves the function.
//
// Used by netlify/functions/backup-weekly.mts (the weekly schedule) and
// netlify/functions/backup-now.mts (an optional manual trigger). The file is
// opened again with scripts/decrypt-backup.mjs; docs/BACKUPS.md is the
// restore guide. Node built-ins only, no packages.

