// ---------------------------------------------------------------------------
// File format (version 1)
//
//   bytes 0-3    "CNBK"                      magic
//   byte  4      0x01                        format version
//   bytes 5-20   salt (16 random bytes)      PBKDF2 salt
//   bytes 21-32  IV (12 random bytes)        AES-GCM nonce
//   bytes 33..   ciphertext                  AES-256-GCM of the gzipped JSON
//   last 16      authentication tag
//
// Key: PBKDF2-HMAC-SHA256, 600,000 iterations, 32 bytes, over the passphrase
// (leading and trailing spaces removed, Unicode NFC). The 33 header bytes are
// the GCM additional data, so a changed header is detected like a changed
// body. scripts/decrypt-backup.mjs mirrors these constants.
// ---------------------------------------------------------------------------

export const FORMAT = {
  magic: Buffer.from("CNBK", "ascii"),
  version: 1,
  saltBytes: 16,
  ivBytes: 12,
  tagBytes: 16,
  iterations: 600_000,
  digest: "sha256",
  keyBytes: 32
};
export const HEADER_BYTES = FORMAT.magic.length + 1 + FORMAT.saltBytes + FORMAT.ivBytes;

export function normalizePassphrase(passphrase) {
  return String(passphrase ?? "").normalize("NFC").trim();
}

// Derives the key once, so it can run while the tables are being read.
export async function prepareKey(passphrase, salt = randomBytes(FORMAT.saltBytes)) {
  const key = await pbkdf2Async(normalizePassphrase(passphrase), salt, FORMAT.iterations, FORMAT.keyBytes, FORMAT.digest);
  return { salt, key };
}

export function encryptWithKey(plain, { salt, key }, iv = randomBytes(FORMAT.ivBytes)) {
  const header = Buffer.concat([FORMAT.magic, Buffer.from([FORMAT.version]), salt, iv]);
  const cipher = createCipheriv("aes-256-gcm", key, iv);
  cipher.setAAD(header);
  const body = Buffer.concat([cipher.update(plain), cipher.final()]);
  return Buffer.concat([header, body, cipher.getAuthTag()]);
}

export async function encryptBackup(plain, passphrase) {
  return encryptWithKey(plain, await prepareKey(passphrase));
}

